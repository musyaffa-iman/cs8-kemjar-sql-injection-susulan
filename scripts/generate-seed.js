// Generate insert.sql + kunci jawaban CSV untuk Varian B.
// Pemakaian: node scripts/generate-seed.js [path_roster_csv] [--force]
// Roster default: ../CS8-Kemjar-SQL-Injection/kunci_jawaban_flags.csv
// (kolom: ID,Nama Lengkap,First Name,Username,Password,Email,Flag)
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const args = process.argv.slice(2);
const force = args.includes("--force");
const rosterPath = args.find((a) => !a.startsWith("--")) ||
  path.join(__dirname, "..", "..", "CS8-Kemjar-SQL-Injection", "kunci_jawaban_flags.csv");

const root = path.join(__dirname, "..");
const sqlOut = path.join(root, "insert.sql");
const csvOut = path.join(root, "docs-asisten", "kunci_jawaban_flags_B.csv");

if (!force && (fs.existsSync(sqlOut) || fs.existsSync(csvOut))) {
  console.error("insert.sql / kunci CSV sudah ada. Pakai --force untuk generate ulang (password & flag akan BERUBAH).");
  process.exit(1);
}

const esc = (s) => String(s).replace(/'/g, "''");
const rows = fs.readFileSync(rosterPath, "utf8").trim().split(/\r?\n/).slice(1).map((line) => {
  const [id, fullName, firstName, username, , email] = line.split(",");
  return {
    id: Number(id),
    fullName: fullName.trim(),
    firstName: firstName.trim(),
    username: username.trim(),
    email: email.trim(),
    password: firstName.trim().toLowerCase() + crypto.randomInt(1000, 10000),
    flag: `NETLAB{cs8b_${crypto.randomBytes(8).toString("hex")}}`,
  };
});

const adminId = Math.max(...rows.map((r) => r.id)) + 1;
const adminPass = "Adm!n" + crypto.randomBytes(4).toString("hex");

let sql = `-- CS8 Varian B - generated by scripts/generate-seed.js
DROP TABLE IF EXISTS public.flag_vault;
DROP TABLE IF EXISTS public.accounts;

CREATE TABLE public.accounts (
    id SERIAL PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    username VARCHAR(255) UNIQUE NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL DEFAULT 'student'
);

CREATE TABLE public.flag_vault (
    id SERIAL PRIMARY KEY,
    account_id INT REFERENCES public.accounts(id) ON DELETE CASCADE,
    flag VARCHAR(255) NOT NULL,
    is_validated BOOLEAN DEFAULT FALSE
);

INSERT INTO public.accounts (id, full_name, username, email, password, role) VALUES
`;
sql += rows.map((r) => `(${r.id}, '${esc(r.firstName)}', '${esc(r.username)}', '${esc(r.email)}', '${esc(r.password)}', 'student')`)
  .concat(`(${adminId}, 'Lab Assistant', 'netlab_admin', 'admin@netlab.test', '${adminPass}', 'admin')`)
  .join(",\n") + ";\n\n";
sql += "SELECT setval('accounts_id_seq', (SELECT MAX(id) FROM accounts));\n\n";
sql += "INSERT INTO public.flag_vault (account_id, flag, is_validated) VALUES\n";
sql += rows.map((r) => `(${r.id}, '${r.flag}', FALSE)`).join(",\n") + ";\n";

const csv = ["ID,Nama Lengkap,First Name,Username,Password,Email,Flag"]
  .concat(rows.map((r) => [r.id, r.fullName, r.firstName, r.username, r.password, r.email, r.flag].join(",")))
  .concat(`${adminId},Lab Assistant,Lab Assistant,netlab_admin,${adminPass},admin@netlab.test,-`)
  .join("\n") + "\n";

fs.mkdirSync(path.dirname(csvOut), { recursive: true });
fs.writeFileSync(sqlOut, sql);
fs.writeFileSync(csvOut, csv);
console.log(`✅ ${rows.length} akun + 1 admin -> ${sqlOut}\n✅ Kunci -> ${csvOut}`);
